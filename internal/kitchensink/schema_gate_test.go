package kitchensink

import (
	"fmt"
	"slices"
	"strings"
	"testing"

	"github.com/KeisukeFD/fizz/internal/plan"
)

// metaSchemaProblems builds the document of c and returns every
// meta-schema or lint failure. Cases that do not register cleanly
// (Panics) produce no document and are reported as nil.
func metaSchemaProblems(c Case) []string {
	f := c.newFizz()
	if _, panicked := safeRegister(c, f); panicked {
		return nil
	}
	doc, err := BuildSpec(f)
	if err != nil {
		return []string{"build spec: " + err.Error()}
	}
	return MetaProblems(doc)
}

// TestAllCaseDocsValid validates the document generated by every case
// without Crashes against the OAS 3.2 meta-schema and the lints. A case
// without FixedBy must validate; a case with FixedBy is reported only.
func TestAllCaseDocsValid(t *testing.T) {
	plan.Pending(t, "P2.6", func(tb testing.TB) {
		var checked, failed, known int
		kinds := map[string]int{}
		for _, c := range cases {
			if c.Crashes {
				continue
			}
			checked++
			problems := metaSchemaProblems(c)
			if len(problems) == 0 {
				continue
			}
			failed++
			for _, p := range problems {
				kinds[strings.SplitN(p, ":", 2)[0]]++
			}
			msg := strings.Join(problems, "\n")
			if c.FixedBy != "" {
				known++
				tb.Logf("%s: not valid yet (fixed by %s):\n%s", c.Name, c.FixedBy, msg)
				continue
			}
			tb.Errorf("%s: generated document is not valid OAS 3.2.1:\n%s", c.Name, msg)
		}
		var ks []string
		for k, n := range kinds {
			ks = append(ks, fmt.Sprintf("%s=%d", k, n))
		}
		slices.Sort(ks)
		tb.Logf("meta-schema gate: %d docs checked, %d failing (%d with FixedBy) [%s]",
			checked, failed, known, strings.Join(ks, " "))
	})
}
