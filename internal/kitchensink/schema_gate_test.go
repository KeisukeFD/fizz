package kitchensink

import (
	"fmt"
	"slices"
	"strings"
	"testing"

	"github.com/wI2L/fizz"
	"github.com/wI2L/fizz/internal/specvalidate"
)

// metaSchemaProblems builds the document of c and returns every
// meta-schema or lint failure. Cases that do not register cleanly
// (Panics) produce no document and are reported as nil.
func metaSchemaProblems(c Case) []string {
	f := fizz.New()
	if _, panicked := safeRegister(c, f); panicked {
		return nil
	}
	doc, err := buildSpec(f)
	if err != nil {
		return []string{"build spec: " + err.Error()}
	}
	var problems []string
	for _, check := range []struct {
		name string
		fn   func([]byte) error
	}{
		{"validate", specvalidate.Validate},
		{"stray-null", specvalidate.LintNoStrayNull},
		{"nullable", specvalidate.LintNoNullable},
		{"component-names", specvalidate.LintComponentNames},
	} {
		if err := check.fn(doc); err != nil {
			problems = append(problems, check.name+": "+strings.ReplaceAll(err.Error(), "\n", "\n  "))
		}
	}
	return problems
}

// TestAllCaseDocsValid validates the document generated by every case
// without Crashes against the OAS 3.2 meta-schema and the lints. A case
// without FixedBy must validate; a case with FixedBy is reported only.
func TestAllCaseDocsValid(t *testing.T) {
	t.Skip("fixed by P2.6")

	var checked, failed, known int
	kinds := map[string]int{}
	for _, c := range cases {
		if c.Crashes {
			continue
		}
		t.Run(c.Name, func(t *testing.T) {
			checked++
			problems := metaSchemaProblems(c)
			if len(problems) == 0 {
				return
			}
			failed++
			for _, p := range problems {
				kinds[strings.SplitN(p, ":", 2)[0]]++
			}
			msg := strings.Join(problems, "\n")
			if c.FixedBy != "" {
				known++
				t.Logf("not valid yet (fixed by %s):\n%s", c.FixedBy, msg)
				return
			}
			t.Error("generated document is not valid OAS 3.2.1:\n" + msg)
		})
	}
	var ks []string
	for k, n := range kinds {
		ks = append(ks, fmt.Sprintf("%s=%d", k, n))
	}
	slices.Sort(ks)
	t.Logf("meta-schema gate: %d docs checked, %d failing (%d with FixedBy) [%s]",
		checked, failed, known, strings.Join(ks, " "))
}
